"""Advanced Drop Search skin from the supplied re_search_monster_drop.uif (uif_in\\).
Output: drop_ui\\*.pus + drop_layout.h   (client folder: JstKO\\drop_ui)
Usage: python build_drop_uif.py
"""
import os

import uifskin as S

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'drop_ui')
W, H = 540, 498

nodes = S.load_uif('re_search_monster_drop.uif')
BUTTONS = ('btn_next', 'btn_previously', 'btn_left', 'btn_right', 'btn_close', 'btn_search', 'btn_save', 'btn_reset')
DYN = ('percent_', 'str_page', 'text_page', 'txt_monster_name', 'edit_search')


def dynamic(e):
    if e.type == 'STRING' and e.id.startswith(DYN):
        return True
    if e.type == 'BUTTON' and e.id in BUTTONS:
        return True
    if e.type == 'EDIT':
        return True
    return False


bg = S.compose(nodes, (W, H), (0, 0), skip=dynamic)
S.save_pus(bg, os.path.join(OUT, 'bg.pus'))
bg.save(os.path.join(HERE, '..', 'uif_out', 'drop_bg.png'))

for bid, prefix in (('btn_next', 'next'), ('btn_previously', 'prev'), ('btn_left', 'left'), ('btn_right', 'right'),
                    ('btn_close', 'close'), ('btn_search', 'search'), ('btn_save', 'save'), ('btn_reset', 'reset')):
    b = S.find(nodes, bid)
    for st, k in ((0, 'n'), (1, 'd'), (2, 'o'), (3, 'x')):
        img = S.state_image(b, st)
        if img is not None:
            S.save_pus(img, os.path.join(OUT, '%s_%s.pus' % (prefix, k)))

L = ['// Generated by build_drop_uif.py from uif_in\\re_search_monster_drop.uif -- do not edit by hand.\n#pragma once\n',
     'static const int DP_W = %d, DP_H = %d;\n' % (W, H)]


def add(name, e):
    L.append(S.header_line(name, S.rect_of(e)))


add('DP_EDIT', S.find(nodes, 'edit_search'))
add('DP_SEARCH', S.find(nodes, 'btn_search'))
add('DP_LIST', S.find(nodes, 'Drop_list'))
add('DP_MONNAME', S.find(nodes, 'txt_monster_name'))
add('DP_PREV', S.find(nodes, 'btn_previously'))
add('DP_NEXT', S.find(nodes, 'btn_next'))
add('DP_PAGE', S.find(nodes, 'text_page'))
add('DP_CLOSE', S.find(nodes, 'btn_close'))
add('DP_BLEFT', S.find(nodes, 'btn_left'))
add('DP_BRIGHT', S.find(nodes, 'btn_right'))
add('DP_BPAGE', S.find(nodes, 'str_page'))
add('DP_RESET', S.find(nodes, 'btn_reset'))
add('DP_SAVE', S.find(nodes, 'btn_save'))
areas = [S.find(nodes, 'bArea%d' % i) for i in range(1, 26)]
L.append('static const int DP_CELL[25][4] = {\n%s };\n' % ',\n'.join('    { %d, %d, %d, %d }' % S.rect_of(a) for a in areas))
pcts = [S.find(nodes, 'percent_%d' % i) for i in range(1, 26)]
L.append('static const int DP_PCT[25][4] = {\n%s };\n' % ',\n'.join('    { %d, %d, %d, %d }' % S.rect_of(a) for a in pcts))
slots = []
for i in range(1, 11):
    base = S.find(nodes, 'base%d' % i)
    slots.append(next(k for k in S.walk(base.children) if k.id == 'area'))
L.append('static const int DP_BSLOT[10][4] = {\n%s };\n' % ',\n'.join('    { %d, %d, %d, %d }' % S.rect_of(a) for a in slots))
with open(os.path.join(HERE, 'drop_layout.h'), 'w') as f:
    f.write(''.join(L))
print('drop uif skin ->', OUT)
