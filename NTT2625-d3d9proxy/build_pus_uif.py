"""Power Up Store skin from the supplied re_powerupstore.uif (uif_in\\).
Output: pus_ui\\bg.pus + u_*.pus button sprites + pus_layout.h   (client folder: HopeGuard\\pus_ui)
Usage: python build_pus_uif.py
"""
import os
import shutil

from PIL import Image

import uifskin as S

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'pus_ui')
W, H = 1042, 621

nodes = S.load_uif('re_powerupstore.uif')
DYN_STR = ('txt_page', 'txt_cash', 'txt_tl_balance', 'text_basket_total_price', 'txt_search', 'esncode')


def dynamic(e):
    if e.type == 'BUTTON':
        return True
    if e.type == 'BASE' and (e.id.startswith('items') or e.id.startswith('purchase_list')
                             or e.id in ('base_refund', 'shopping_confirm', 'Basket_confirm')):
        return True
    if e.type == 'STRING' and e.id in DYN_STR:
        return True
    return False


bg = S.compose(nodes, (W, H), (0, 0), skip=dynamic)
S.save_pus(bg, os.path.join(OUT, 'bg.pus'))
bg.save(os.path.join(HERE, '..', 'uif_out', 'pus_bg.png'))


def sprites(btn, prefix):
    for st, k in ((0, 'n'), (1, 'd'), (2, 'o'), (3, 'x')):
        img = S.state_image(btn, st)
        if img is not None:
            S.save_pus(img, os.path.join(OUT, 'u_%s_%s.pus' % (prefix, k)))


def item_nodes(base):
    """the four product cards of a row base, left to right"""
    cards = [c for c in base.children if c.type == 'IMAGE' and c.id.startswith('item') and c.id[4:].isdigit()]
    return sorted(cards, key=lambda c: c.rect[0])


rows = [S.find(nodes, 'items%d' % i) for i in range(1, 5)]
first = item_nodes(rows[0])[0]
# product card frame (the card image itself, without icon / texts / buttons)
card = Image.new('RGBA', (first.rect[2] - first.rect[0], first.rect[3] - first.rect[1]), (0, 0, 0, 0))
S.draw_image(card, first, (-first.rect[0], -first.rect[1]))
S.save_pus(card, os.path.join(OUT, 'u_card.pus'))

buy = next(c for c in first.children if c.id == 'btn_purchase')
bask = next(c for c in first.children if c.id == 'btn_add_basket')
sprites(buy, 'buy')
sprites(bask, 'bask')
for bid, prefix in (('btn_clearall', 'clear'), ('btn_tab1', 'tab'), ('btn_useesn', 'esn'), ('btn_buyall', 'buyall'),
                    ('btn_search', 'search'), ('btn_next', 'next'), ('btn_previous', 'prev')):
    sprites(S.find(nodes, bid), prefix)
pl1 = S.find(nodes, 'purchase_list1')
sprites(next(c for c in pl1.children if c.id == 'btn_cancel'), 'cancel')
frame = next(c for c in pl1.children if c.type == 'IMAGE' and c.id == '')
fimg = Image.new('RGBA', (frame.rect[2] - frame.rect[0], frame.rect[3] - frame.rect[1]), (0, 0, 0, 0))
S.draw_image(fimg, frame, (-frame.rect[0], -frame.rect[1]))
S.save_pus(fimg, os.path.join(OUT, 'u_cartframe.pus'))

def crop_sprite(root, skip, rect, name):
    full = S.compose([root], (W, H), (0, 0), skip=skip)
    S.save_pus(full.crop(rect), os.path.join(OUT, name))


def btn(root_id, parent, prefix):
    b = next(c for c in S.find(nodes, parent).children if c.id == root_id)
    sprites(b, prefix)
    return b


# refund page (both panels), rows are drawn dynamically
refund = S.find(nodes, 'base_refund')
crop_sprite(refund, lambda e: e.type == 'BASE' and e.id.startswith('refund_items_'), (262, 122, 1034, 587), 'u_rbg.pus')
r0 = next(c for c in refund.children if c.id == 'refund_items_0')
frm = next(c for c in r0.children if c.type == 'IMAGE' and c.id == '' and 'ringupgrade' in (c.tex or ''))
rf = Image.new('RGBA', (frm.rect[2] - frm.rect[0], frm.rect[3] - frm.rect[1]), (0, 0, 0, 0))
S.draw_image(rf, frm, (-frm.rect[0], -frm.rect[1]))
S.save_pus(rf, os.path.join(OUT, 'u_rframe.pus'))
bf = next(c for c in r0.children if c.type == 'IMAGE' and c.id == '' and 'skill04' in (c.tex or ''))
rb = Image.new('RGBA', (bf.rect[2] - bf.rect[0], bf.rect[3] - bf.rect[1]), (0, 0, 0, 0))
S.draw_image(rb, bf, (-bf.rect[0], -bf.rect[1]))
S.save_pus(rb, os.path.join(OUT, 'u_rbtnframe.pus'))
sprites(next(c for c in r0.children if c.id == 'btn_ireturn'), 'ret')
sprites(S.find(nodes, 'btn_close'), 'close')

# purchase dialog (frame + static texts) and basket dialog
shop = S.find(nodes, 'shopping_confirm')
DLG_DYN = ('shopping_after', 'shopping_quantity', 'shopping_name', 'shopping_price', 'str_count', 'shopping_icon')
crop_sprite(shop, lambda e: e.type == 'BUTTON' or e.id in DLG_DYN, (449, 179, 779, 465), 'u_dlg.pus')
for bid, pre in (('btn_confirm', 'dok'), ('btn_cancel', 'dno'), ('btn_up', 'dup'), ('btn_down', 'ddown')):
    btn(bid, 'shopping_confirm', pre)
bask_d = S.find(nodes, 'Basket_confirm')
crop_sprite(bask_d, lambda e: e.type == 'BUTTON' or e.id == 'text_basket_total_price'
            or (e.type == 'STRING' and e.text.startswith('You cannot')), (449, 179, 779, 465), 'u_bdlg.pus')
btn('btn_all_confirm', 'Basket_confirm', 'bok')
btn('btn_cancel', 'Basket_confirm', 'bno')

L = ['// Generated by build_pus_uif.py from uif_in\\re_powerupstore.uif -- do not edit by hand.\n#pragma once\n',
     'struct PusRect { int l, t, r, b; };\n',
     'static const int PUS_W = %d, PUS_H = %d;\n' % (W, H)]


def R(e):
    l, t, r, b = S.rect_of(e)
    return '{ %d, %d, %d, %d }' % (l, t, r, b)


def single(name, id_, type_=None):
    e = next(n for n in S.walk(nodes) if n.id == id_ and (type_ is None or n.type == type_))
    L.append('static const PusRect %s = %s;\n' % (name, R(e)))


single('PUS_EDIT_SEARCH', 'edit_search', 'EDIT')
single('PUS_BTN_SEARCH', 'btn_search')
single('PUS_EDIT_ESN', 'esncode', 'EDIT')
single('PUS_BTN_ESN', 'btn_useesn')
single('PUS_TXT_CASH', 'txt_cash')
single('PUS_TXT_TL', 'txt_tl_balance')
single('PUS_TXT_PAGE', 'txt_page')
single('PUS_TXT_TOTAL', 'text_basket_total_price')
single('PUS_NEXT', 'btn_next')
single('PUS_PREV', 'btn_previous')
single('PUS_CLEAR', 'btn_clearall')
single('PUS_BUYALL', 'btn_buyall')
single('PUS_REFUND', 'btn_refund')
single('PUS_RESELLER', 'btn_reseller')
L.append('static const PusRect PUS_TABS[5] = { %s };\n' % ', '.join(R(S.find(nodes, 'btn_tab%d' % i)) for i in range(1, 6)))
L.append('static const PusRect PUS_CLOSE = { %d, 8, %d, 34 };\n' % (W - 46, W - 20))

slots = []
for base in rows:
    for card_n in item_nodes(base):
        ch = {c.id: c for c in card_n.children}
        slots.append((card_n, ch))
L.append('struct PusSlot { PusRect card, icon, name, price, qty, buy, bask; };\n')
L.append('static const PusSlot PUS_SLOTS[16] = {\n')
for card_n, ch in slots:
    L.append('    { %s, %s, %s, %s, %s, %s, %s },\n' % (R(card_n), R(ch['item_icon']), R(ch['item_name']), R(ch['item_price']),
                                                     R(ch['item_quantitiy']), R(ch['btn_purchase']), R(ch['btn_add_basket'])))
L.append('};\n')

L.append('struct PusCartRow { PusRect row, cancel, name, price, frame, icon; };\n')
L.append('static const PusCartRow PUS_CART[7] = {\n')
for i in range(1, 8):
    b = S.find(nodes, 'purchase_list%d' % i)
    ch = {}
    for c in b.children:
        ch.setdefault(c.id or ('anon_' + c.type), c)
    L.append('    { %s, %s, %s, %s, %s, %s },\n' % (R(b), R(ch['btn_cancel']), R(ch['shopping_name']), R(ch['shopping_price']),
                                                   R(ch['anon_IMAGE']), R(ch['item_icon'])))
L.append('};\n')
def child(parent, id_):
    return next(c for c in S.walk([parent]) if c.id == id_)


L.append('static const PusRect PUS_DLG = %s;\n' % R(shop))
for name, id_ in (('ICON', 'shopping_icon'), ('NAME', 'shopping_price'), ('PRICE', 'shopping_name'), ('QTY', 'shopping_quantity'),
                  ('AFTER', 'shopping_after'), ('COUNT', 'str_count'), ('UP', 'btn_up'), ('DOWN', 'btn_down'),
                  ('OK', 'btn_confirm'), ('CANCEL', 'btn_cancel'), ('GIFT', 'txt_gift_name')):
    L.append('static const PusRect PUS_DLG_%s = %s;\n' % (name, R(child(shop, id_))))
L.append('static const PusRect PUS_BDLG_TEXT = { 500, 265, 733, 337 };\n')
L.append('static const PusRect PUS_BDLG_TOTAL = %s;\n' % R(child(bask_d, 'text_basket_total_price')))
L.append('static const PusRect PUS_BDLG_OK = %s;\n' % R(child(bask_d, 'btn_all_confirm')))
L.append('static const PusRect PUS_BDLG_CANCEL = %s;\n' % R(child(bask_d, 'btn_cancel')))
L.append('static const PusRect PUS_RBG = { 262, 122, 1034, 587 };\n')
L.append('struct PusRefundRow { PusRect icon, name, price, ret; };\n')
L.append('static const PusRefundRow PUS_RROWS[18] = {\n')
rrows = sorted([c for c in refund.children if c.type == 'BASE'], key=lambda c: (c.rect[0] > 400, c.rect[1]))
for c in rrows:
    k = {x.id: x for x in c.children}
    n = c.id.split('_')[-1]
    L.append('    { %s, %s, %s, %s },\n' % (R(k['item_icon']), R(k['refund_item' + n]), R(k['refund_price' + n]), R(k['btn_ireturn'])))
L.append('};\n')
with open(os.path.join(HERE, 'pus_layout.h'), 'w') as f:
    f.write(''.join(L))
print('pus skin ->', OUT, '(%d product cards)' % len(slots))
