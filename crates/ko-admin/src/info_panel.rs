//! "Bilgi Paneli" page: the entries of the game client's right-top info list (title button that
//! unfolds a description when clicked, see `ko_protocol::info_panel`). The game server sends every
//! enabled row of `info_panel_entry` to the players; a save here queues an `info_panel_reload`
//! admin_command, so a running server updates everyone without a restart.
//!
//! The texts are normalised with the very same `ko_protocol::info_panel` functions the game
//! server uses before it puts them on the wire, so what is saved is exactly what players see
//! (Turkish letters become ASCII, line breaks become `|`, length / line limits applied). The live
//! CLAN PREMIUM entry is generated by the server and cannot be created here.

use std::net::SocketAddr;

use axum::{
    extract::{ConnectInfo, Path, State},
    http::HeaderMap,
    routing::{get, post},
    Json, Router,
};
use ko_protocol::info_panel as wire;
use serde::Deserialize;
use serde_json::{json, Value};
use sqlx::Row;

use crate::legacy::{audit, auth, queue_command, ApiError};
use crate::App;

/// Most rows the table may hold (the game server reads the first 40 by order).
const MAX_ROWS: i64 = 40;
/// Reserved by the live clan premium entry (`handler::info_panel::CLAN_PREMIUM_TITLE`).
const RESERVED_TITLE: &str = "CLAN PREMIUM";

pub fn routes() -> Router<App> {
    Router::new()
        .route(
            "/jstkoadminpanel/api/info-panel",
            get(list).post(create),
        )
        .route("/jstkoadminpanel/api/info-panel/reorder", post(reorder))
        .route(
            "/jstkoadminpanel/api/info-panel/{id}",
            post(update).delete(remove),
        )
}

type R = Result<Json<Value>, ApiError>;

fn internal<E: std::fmt::Display>(what: &'static str) -> impl Fn(E) -> ApiError {
    move |e| {
        tracing::warn!(error = %e, "{what}");
        ApiError::Internal
    }
}

#[derive(Deserialize)]
struct EntryIn {
    title: String,
    description: String,
    #[serde(default = "yes")]
    enabled: bool,
    #[serde(default)]
    requires_clan_premium: bool,
}
fn yes() -> bool {
    true
}

/// Normalised (title, description) or `BadRequest` when nothing usable is left / reserved title.
fn normalise(p: &EntryIn) -> Result<(String, String), ApiError> {
    let title = wire::sanitize_title(&p.title);
    let description = wire::sanitize_description(&p.description);
    if title.is_empty() || description.is_empty() || title.eq_ignore_ascii_case(RESERVED_TITLE) {
        return Err(ApiError::BadRequest);
    }
    Ok((title, description))
}

fn row_json(r: &sqlx::postgres::PgRow) -> Value {
    json!({
        "id": r.try_get::<i64, _>("id").unwrap_or(0),
        "sort_order": r.try_get::<i32, _>("sort_order").unwrap_or(0),
        "title": r.try_get::<String, _>("title").unwrap_or_default(),
        "description": r.try_get::<String, _>("description").unwrap_or_default(),
        "enabled": r.try_get::<bool, _>("enabled").unwrap_or(false),
        "requires_clan_premium": r.try_get::<bool, _>("requires_clan_premium").unwrap_or(false),
    })
}

async fn list(headers: HeaderMap, State(app): State<App>) -> R {
    auth(&headers, false)?;
    let rows = sqlx::query(
        "SELECT id, sort_order, title, description, enabled, requires_clan_premium \
         FROM info_panel_entry ORDER BY sort_order, id",
    )
    .fetch_all(&app.pool)
    .await
    .map_err(internal("info-panel list"))?;
    let entries: Vec<Value> = rows.iter().map(row_json).collect();
    Ok(Json(json!({
        "entries": entries,
        "limits": {
            "title": wire::MAX_TITLE_CHARS,
            "description": wire::MAX_DESCRIPTION_CHARS,
            "lines": wire::MAX_DESCRIPTION_LINES,
            "shown": wire::MAX_PANEL_ENTRIES,
            "rows": MAX_ROWS,
            "reserved_title": RESERVED_TITLE,
        },
    })))
}

async fn create(
    headers: HeaderMap,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(app): State<App>,
    Json(p): Json<EntryIn>,
) -> R {
    let (_, s) = auth(&headers, true)?;
    let (title, description) = normalise(&p)?;
    let mut tx = app.pool.begin().await.map_err(internal("tx"))?;
    let count: i64 = sqlx::query_scalar("SELECT count(*) FROM info_panel_entry")
        .fetch_one(&mut *tx)
        .await
        .map_err(internal("info-panel count"))?;
    if count >= MAX_ROWS {
        return Err(ApiError::BadRequest);
    }
    let row = sqlx::query(
        "INSERT INTO info_panel_entry(sort_order, title, description, enabled, requires_clan_premium) \
         VALUES((SELECT COALESCE(MAX(sort_order), 0) + 10 FROM info_panel_entry), $1, $2, $3, $4) \
         RETURNING id, sort_order, title, description, enabled, requires_clan_premium",
    )
    .bind(&title)
    .bind(&description)
    .bind(p.enabled)
    .bind(p.requires_clan_premium)
    .fetch_one(&mut *tx)
    .await
    .map_err(internal("info-panel create"))?;
    let entry = row_json(&row);
    audit(&mut tx, &s.actor, "info_panel.create", &title, json!({"entry": entry}), peer.ip()).await?;
    tx.commit().await.map_err(internal("commit"))?;
    let reload = queue_command(&app.pool, "info_panel_reload", json!({})).await?;
    Ok(Json(json!({"ok": true, "entry": entry, "reload_id": reload})))
}

async fn update(
    headers: HeaderMap,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(app): State<App>,
    Path(id): Path<i64>,
    Json(p): Json<EntryIn>,
) -> R {
    let (_, s) = auth(&headers, true)?;
    let (title, description) = normalise(&p)?;
    let mut tx = app.pool.begin().await.map_err(internal("tx"))?;
    let row = sqlx::query(
        "UPDATE info_panel_entry SET title=$2, description=$3, enabled=$4, requires_clan_premium=$5, updated_at=NOW() \
         WHERE id=$1 RETURNING id, sort_order, title, description, enabled, requires_clan_premium",
    )
    .bind(id)
    .bind(&title)
    .bind(&description)
    .bind(p.enabled)
    .bind(p.requires_clan_premium)
    .fetch_optional(&mut *tx)
    .await
    .map_err(internal("info-panel update"))?
    .ok_or(ApiError::NotFound)?;
    let entry = row_json(&row);
    audit(&mut tx, &s.actor, "info_panel.update", &id.to_string(), json!({"entry": entry}), peer.ip()).await?;
    tx.commit().await.map_err(internal("commit"))?;
    let reload = queue_command(&app.pool, "info_panel_reload", json!({})).await?;
    Ok(Json(json!({"ok": true, "entry": entry, "reload_id": reload})))
}

async fn remove(
    headers: HeaderMap,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(app): State<App>,
    Path(id): Path<i64>,
) -> R {
    let (_, s) = auth(&headers, true)?;
    let mut tx = app.pool.begin().await.map_err(internal("tx"))?;
    let row = sqlx::query("DELETE FROM info_panel_entry WHERE id=$1 RETURNING title")
        .bind(id)
        .fetch_optional(&mut *tx)
        .await
        .map_err(internal("info-panel delete"))?
        .ok_or(ApiError::NotFound)?;
    let title: String = row.try_get("title").unwrap_or_default();
    audit(&mut tx, &s.actor, "info_panel.delete", &id.to_string(), json!({"title": title}), peer.ip()).await?;
    tx.commit().await.map_err(internal("commit"))?;
    let reload = queue_command(&app.pool, "info_panel_reload", json!({})).await?;
    Ok(Json(json!({"ok": true, "reload_id": reload})))
}

#[derive(Deserialize)]
struct ReorderIn {
    ids: Vec<i64>,
}

/// New order = the position in `ids`. Must name every existing row exactly once.
async fn reorder(
    headers: HeaderMap,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(app): State<App>,
    Json(p): Json<ReorderIn>,
) -> R {
    let (_, s) = auth(&headers, true)?;
    if p.ids.is_empty() || p.ids.len() as i64 > MAX_ROWS {
        return Err(ApiError::BadRequest);
    }
    let mut sorted = p.ids.clone();
    sorted.sort_unstable();
    sorted.dedup();
    if sorted.len() != p.ids.len() {
        return Err(ApiError::BadRequest);
    }
    let mut tx = app.pool.begin().await.map_err(internal("tx"))?;
    let mut existing: Vec<i64> = sqlx::query_scalar("SELECT id FROM info_panel_entry FOR UPDATE")
        .fetch_all(&mut *tx)
        .await
        .map_err(internal("info-panel ids"))?;
    existing.sort_unstable();
    if existing != sorted {
        return Err(ApiError::Conflict);
    }
    for (i, id) in p.ids.iter().enumerate() {
        sqlx::query("UPDATE info_panel_entry SET sort_order=$2, updated_at=NOW() WHERE id=$1")
            .bind(id)
            .bind((i as i32 + 1) * 10)
            .execute(&mut *tx)
            .await
            .map_err(internal("info-panel reorder"))?;
    }
    audit(&mut tx, &s.actor, "info_panel.reorder", "order", json!({"ids": p.ids}), peer.ip()).await?;
    tx.commit().await.map_err(internal("commit"))?;
    let reload = queue_command(&app.pool, "info_panel_reload", json!({})).await?;
    Ok(Json(json!({"ok": true, "reload_id": reload})))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn input(title: &str, description: &str) -> EntryIn {
        EntryIn { title: title.into(), description: description.into(), enabled: true, requires_clan_premium: false }
    }

    #[test]
    fn normalise_applies_the_wire_rules() {
        let (t, d) = normalise(&input("  Çarşamba Şöleni ", "Satır 1\r\nSatır 2")).unwrap();
        assert_eq!(t, "Carsamba Soleni");
        assert_eq!(d, "Satir 1|Satir 2");
    }

    #[test]
    fn normalise_rejects_empty_and_reserved() {
        assert!(normalise(&input("", "x")).is_err());
        assert!(normalise(&input("x", "   ")).is_err());
        assert!(normalise(&input("\u{1F600}", "x")).is_err());
        assert!(normalise(&input("Clan Premium", "x")).is_err());
        assert!(normalise(&input(" clan  premium ", "x")).is_err());
    }

    #[test]
    fn normalise_bounds_long_input() {
        let (t, d) = normalise(&input(&"T".repeat(1000), &"d\n".repeat(1000))).unwrap();
        assert!(t.chars().count() <= wire::MAX_TITLE_CHARS);
        assert!(d.chars().count() <= wire::MAX_DESCRIPTION_CHARS);
        assert!(d.split('|').count() <= wire::MAX_DESCRIPTION_LINES);
    }
}
