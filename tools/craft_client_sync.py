"""Compares the client's craft formulas (Data\\mixtable_us.tbl + MixLargeTbl_us.tbl) with the server table
item_special_sewing and writes

  migrations/<stamp>_craft_client_mix.sql   craft_client_mix (one row per client formula + match status)
  docs/data/craft_no_client_formula.csv     server recipes the client table has no formula for (postponed)
  docs/data/craft_client_missing_on_server.csv  client formulas the server cannot craft yet (need rate / item)
  docs/CRAFT_FORMULA_LISTS.md               the summary

Inputs (made with tbl_dump / psql, see docs/CRAFT_FORMULA_LISTS.md):  %TEMP%\\mix.txt, mixlarge.txt, sewing.csv, sewitems.csv
Usage: python tools/craft_client_sync.py
"""
import csv
import io
import os
import re
import sys
from collections import defaultdict

TMP = os.environ.get('TEMP', '.')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STAMP = '20261022100000'


def parse_dump(path):
    rows = []
    for line in open(path, encoding='utf-8', errors='replace'):
        if not line.startswith('row='):
            continue
        fields = {}
        for m in re.finditer(r'c(\d+)=("(?:[^"\\]|\\.)*"|-?\d+)', line):
            v = m.group(2)
            fields[int(m.group(1))] = v[1:-1] if v.startswith('"') else int(v)
        rows.append(fields)
    return rows


mix = parse_dump(os.path.join(TMP, 'mix.txt'))
large = {r[1]: r[2] for r in parse_dump(os.path.join(TMP, 'mixlarge.txt'))}
names = {}
for r in csv.reader(open(os.path.join(TMP, 'sewitems.csv'), encoding='utf-8', errors='replace')):
    if len(r) >= 2 and r[0].isdigit():
        names[int(r[0])] = r[1]

client = []
for r in mix:
    mats = []
    for i in range(10):
        item, cnt = r.get(5 + 2 * i, 0), r.get(6 + 2 * i, 0)
        if item and cnt:
            mats.append((item, cnt))
    client.append({'idx': r[0], 'npc': r[1], 'cat': r[2], 'catname': large.get(r[2], ''), 'name': r[3], 'mats': mats, 'result': r.get(31, 0)})

server = defaultdict(list)   # (npc, sorted mats) -> rows
srows = list(csv.DictReader(open(os.path.join(TMP, 'sewing.csv'), encoding='utf-8', errors='replace')))
for r in srows:
    mats = tuple(sorted((int(r[f'req_item_id_{i}']), int(r[f'req_item_count_{i}'])) for i in range(1, 11) if int(r[f'req_item_id_{i}']) and int(r[f'req_item_count_{i}'])))
    server[(int(r['npc_id']), mats)].append(r)

GENERIC = 810102000   # "Identical Used Accessory": the client formula book shows the 3 identical accessories as this placeholder


def generic_key(npc, mats):
    """server jeweler recipe with 3 identical accessories -> the client's placeholder form"""
    d = dict()
    for i, n in mats:
        d.setdefault(i, 0)
        d[i] += n
    trip = [i for i, n in d.items() if n == 3 and i != GENERIC and i > 300000000 and i < 400000000]
    if npc == 31402 and len(trip) == 1:
        rest = [(i, n) for i, n in mats if i != trip[0]]
        return (npc, tuple(sorted(rest + [(GENERIC, 1)] * 3)))
    return None


server_generic = defaultdict(list)
for (npc, mats), rows in server.items():
    gk = generic_key(npc, mats)
    if gk:
        server_generic[gk].extend(rows)

cl_keys = set()
generic_covered = set()
for c in client:
    key = (c['npc'], tuple(sorted(c['mats'])))
    cl_keys.add(key)
    rows = server.get(key, [])
    if not rows and key in server_generic:
        rows = server_generic[key]
        generic_covered.add(key)
        c['status'] = 'generic'
        c['ns'] = sorted(int(x['n_index']) for x in rows)
        continue
    if not rows:
        c['status'] = 'missing'
        c['ns'] = []
    else:
        results = {int(x['give_item_id']) for x in rows}
        c['status'] = 'ok' if c['result'] in results else 'result_differs'
        c['ns'] = [int(x['n_index']) for x in rows]


def nm(i):
    return names.get(i, str(i))


# ---- migration
def q(s):
    return "'" + str(s).replace("'", "''") + "'"


sql = ['-- Client craft formulas (mixtable_us.tbl) and how the server recipes (item_special_sewing) match them.',
       '-- Generated by tools/craft_client_sync.py; shown on the admin "Craft" page.',
       'DROP TABLE IF EXISTS craft_client_mix;',
       'CREATE TABLE craft_client_mix (',
       '    mix_index    INT PRIMARY KEY,',
       '    npc_id       INT NOT NULL,',
       '    category     INT NOT NULL,',
       "    category_name VARCHAR(80) NOT NULL DEFAULT '',",
       "    name         VARCHAR(120) NOT NULL DEFAULT '',",
       "    materials    JSONB NOT NULL DEFAULT '[]',",
       '    result_item  INT NOT NULL DEFAULT 0,',
       "    status       VARCHAR(20) NOT NULL DEFAULT 'missing',",
       "    server_rows  INT[] NOT NULL DEFAULT '{}'",
       ');',
       'CREATE INDEX idx_craft_client_mix_npc ON craft_client_mix (npc_id);']
for c in client:
    mats = '[' + ','.join('{"id":%d,"count":%d}' % m for m in c['mats']) + ']'
    ns = '{' + ','.join(map(str, c['ns'])) + '}'
    sql.append('INSERT INTO craft_client_mix VALUES (%d,%d,%d,%s,%s,%s::jsonb,%d,%s,%s);' % (
        c['idx'], c['npc'], c['cat'], q(c['catname']), q(c['name']), q(mats), c['result'], q(c['status']), q(ns)))
sql += ["DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'webpanel') THEN EXECUTE 'GRANT SELECT ON craft_client_mix TO webpanel'; END IF; END $$;"]
open(os.path.join(ROOT, 'migrations', f'{STAMP}_craft_client_mix.sql'), 'w', encoding='utf-8', newline='\n').write('\n'.join(sql) + '\n')

# ---- lists
def desc_of(r):
    return r['description']


nocl = []
for (npc, mats), rows in sorted(server.items(), key=lambda kv: (kv[0][0], desc_of(kv[1][0]), int(kv[1][0]['n_index']))):
    if (npc, mats) in cl_keys or (generic_key(npc, mats) in generic_covered):
        continue
    for r in rows:
        nocl.append([npc, desc_of(r), r['n_index'], '; '.join(f'{nm(i)} x{c}' for i, c in mats), r['give_item_id'], nm(int(r['give_item_id'])), r['give_item_count'], int(r['success_rate']) / 100, 'evet' if r['is_shadow_success'] in ('t', 'true', 'True') else 'hayir'])
os.makedirs(os.path.join(ROOT, 'docs', 'data'), exist_ok=True)
with open(os.path.join(ROOT, 'docs', 'data', 'craft_no_client_formula.csv'), 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f)
    w.writerow(['npc', 'aciklama', 'n_index', 'malzemeler', 'sonuc_id', 'sonuc_adi', 'adet', 'oran_yuzde', 'shadow_garanti'])
    w.writerows(nocl)

miss = [c for c in client if c['status'] not in ('ok', 'generic')]
with open(os.path.join(ROOT, 'docs', 'data', 'craft_client_missing_on_server.csv'), 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f)
    w.writerow(['mix_satir', 'npc', 'kategori', 'ad', 'durum', 'malzemeler', 'istemci_sonuc_id', 'istemci_sonuc_adi', 'sunucu_n_index'])
    for c in miss:
        w.writerow([c['idx'], c['npc'], c['catname'], c['name'], c['status'], '; '.join(f'{nm(i)} x{n}' for i, n in c['mats']), c['result'], nm(c['result']), ' '.join(map(str, c['ns']))])

# ---- summary
by_cat = defaultdict(lambda: defaultdict(int))
for c in client:
    by_cat[(c['npc'], c['catname'])][c['status']] += 1
nodesc = defaultdict(int)
for r in nocl:
    nodesc[(r[0], r[1])] += 1
md = ['# Craft formulas: client table vs server', '',
      f'Client formulas (`mixtable_us.tbl`): {len(client)}; server recipes (`item_special_sewing`): {len(srows)}.', '',
      '## Client formulas by category (status against the server)', '',
      '| NPC | Category | OK | Jeweler generic | Result differs | Missing on server |', '|---|---|---|---|---|---|']
for (npc, cat), st in sorted(by_cat.items()):
    md.append(f"| {npc} | {cat} | {st['ok']} | {st['generic']} | {st['result_differs']} | {st['missing']} |")
md += ['', f'## Server recipes with NO formula in the client table ({len(nocl)} rows, postponed)', '',
       'They still craft when the materials are placed by hand; the client formula book does not list them. Full list: `docs/data/craft_no_client_formula.csv`.', '',
       '| NPC | Description | Rows |', '|---|---|---|']
for (npc, d), n in sorted(nodesc.items(), key=lambda kv: -kv[1]):
    md.append(f'| {npc} | {d} | {n} |')
md += ['', f'## Client formulas the server cannot craft yet ({len(miss)})', '',
       'Full list with materials: `docs/data/craft_client_missing_on_server.csv` (needs a rate and/or the right result item).']
open(os.path.join(ROOT, 'docs', 'CRAFT_FORMULA_LISTS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(md) + '\n')
print('client', len(client), 'ok', sum(c['status'] == 'ok' for c in client), 'generic', sum(c['status'] == 'generic' for c in client), 'differs', sum(c['status'] == 'result_differs' for c in client), 'missing', sum(c['status'] == 'missing' for c in client))
print('server rows without client formula', len(nocl))


# ---- recipes for the client formulas the server could not craft (provisional rates, editable in the admin Craft page)
RATE = {"Hepa's Armor": 2500, "Draki's Pendant": 3500, 'Cursed [Craft Weapon Box]': 2700}
DEFAULT_RATE = 3000
ins = ['-- Craft recipes for client formulas (mixtable_us.tbl) that had no server recipe. Rates are PROVISIONAL',
       '-- (Hepa armor 25 %, Draki pendant 35 %, cursed weapon box 27 % like their server siblings, others 30 %);',
       '-- every row is shadow-success like the other Shozin recipes. Change them in the admin "Craft" page.',
       '-- A row is only inserted when every material and the result exist in the item table.']
n = 7000
added = 0
skipped = []
for c in client:
    if c['status'] != 'missing' or c['npc'] not in (19073, 31402) or not c['result'] or not c['mats']:
        skipped.append(c)
        continue
    n += 1
    ids = sorted({i for i, _ in c['mats']} | {c['result']})
    cols = ['n_index', 'description']
    vals = [str(n), q(f"{c['catname'] or c['name']} (client formula)")]
    for k, (i, cnt) in enumerate(c['mats'], 1):
        cols += [f'req_item_id_{k}', f'req_item_count_{k}']
        vals += [str(i), str(cnt)]
    cols += ['give_item_id', 'give_item_count', 'success_rate', 'npc_id', 'is_notice', 'is_shadow_success']
    vals += [str(c['result']), '1', str(RATE.get(c['catname'], DEFAULT_RATE)), str(c['npc']), 'FALSE', 'TRUE']
    ins.append('INSERT INTO item_special_sewing (%s) SELECT %s WHERE (SELECT count(*) FROM item WHERE num IN (%s)) = %d ON CONFLICT (n_index) DO NOTHING;' % (
        ', '.join(cols), ', '.join(vals), ', '.join(map(str, ids)), len(ids)))
    added += 1
ins.append('-- client message row (success / fail text of the formula) for the recipes above and every matched existing recipe')
for c in client:
    if c['ns'] and c['status'] in ('ok', 'generic', 'result_differs'):
        for x in c['ns']:
            ins.append('INSERT INTO item_special_sewing_client_map (n_index, mix_index) VALUES (%d, %d) ON CONFLICT (n_index) DO NOTHING;' % (x, c['idx']))
n2 = 7000
for c in client:
    if c['status'] == 'missing' and c['npc'] in (19073, 31402) and c['result'] and c['mats']:
        n2 += 1
        ins.append('INSERT INTO item_special_sewing_client_map (n_index, mix_index) SELECT %d, %d WHERE EXISTS (SELECT 1 FROM item_special_sewing WHERE n_index = %d) ON CONFLICT (n_index) DO NOTHING;' % (n2, c['idx'], n2))
open(os.path.join(ROOT, 'migrations', f'{STAMP[:-1]}1_craft_client_recipes.sql'), 'w', encoding='utf-8', newline='\n').write('\n'.join(ins) + '\n')
print('recipes generated', added, 'skipped', len(skipped))
