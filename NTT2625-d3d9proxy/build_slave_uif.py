"""Slave Merchant window skin from the supplied slavemerchant.uif (uif_in\\).
Output: slave_ui\\bg.pus + button / icon sprites + slave_layout.h   (client folder: JstKO\\slave_ui)
Usage: python build_slave_uif.py
"""
import os

from PIL import Image

import uifskin as S

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'slave_ui')
W, H = 1032, 617

nodes = S.load_uif('slavemerchant.uif')
DYN = ('txt_valuedelay', 'txt_valuestate', 'text_cashpoint', 'text_gold')


def dynamic(e):
    if e.type == 'BUTTON':
        return True
    if e.type == 'STRING' and (e.id in DYN or e.id.startswith(('st', 'a')) and e.id[1:].isdigit()):
        return True
    return False


bg = S.compose(nodes, (W, H), (0, 0), skip=dynamic)
S.save_pus(bg, os.path.join(OUT, 'bg.pus'))
os.makedirs(os.path.join(HERE, '..', 'uif_out'), exist_ok=True)
bg.save(os.path.join(HERE, '..', 'uif_out', 'slave_bg.png'))

for bid, prefix in (('btn_close', 'close'), ('btn_useslavescroll', 'use'), ('close_merchant', 'closem'), ('btn_cash', 'cash'), ('btn_gold', 'gold')):
    b = S.find(nodes, bid)
    for st, k in ((0, 'n'), (1, 'd'), (2, 'o'), (3, 'x')):
        img = S.state_image(b, st)
        if img is not None:
            S.save_pus(img, os.path.join(OUT, '%s_%s.pus' % (prefix, k)))

# top-bar icon: the gold frame + the portrait of the window, half size
frame = next(e for e in nodes if e.type == 'IMAGE' and e.rect == [460, 363, 544, 450]) if False else None
imgs = [e for e in nodes if e.type == 'IMAGE']
fr = next(e for e in imgs if tuple(e.rect) == (460, 363, 544, 450))
pt = next(e for e in imgs if tuple(e.rect) == (470, 373, 534, 441))
canvas = Image.new('RGBA', (84, 87), (0, 0, 0, 0))
S.draw_image(canvas, fr, (-460, -363))
S.draw_image(canvas, pt, (-460, -363))
icon = canvas.resize((46, 48), Image.LANCZOS)
S.save_pus(icon, os.path.join(OUT, 'icon_n.pus'))
bright = Image.eval(icon.convert('RGB'), lambda v: min(255, int(v * 1.25))).convert('RGBA')
bright.putalpha(icon.split()[3])
S.save_pus(bright, os.path.join(OUT, 'icon_o.pus'))

L = ['// Generated by build_slave_uif.py from uif_in\\slavemerchant.uif -- do not edit by hand.\n#pragma once\n',
     'struct SmRect { int l, t, r, b; };\n',
     'static const int SM_W = %d, SM_H = %d, SM_ICON_W = 46, SM_ICON_H = 48;\n' % (W, H)]


def R(e):
    l, t, r, b = S.rect_of(e)
    return '{ %d, %d, %d, %d }' % (l, t, r, b)


def one(name, id_):
    e = next(n for n in S.walk(nodes) if n.id == id_)
    L.append('static const SmRect %s = %s;\n' % (name, R(e)))


for name, id_ in (('SM_CLOSE', 'btn_close'), ('SM_USE', 'btn_useslavescroll'), ('SM_CLOSEM', 'close_merchant'), ('SM_CASH', 'btn_cash'), ('SM_GOLD', 'btn_gold'),
                  ('SM_STATE', 'txt_valuestate'), ('SM_DELAY', 'txt_valuedelay'), ('SM_CASHTXT', 'text_cashpoint'), ('SM_GOLDTXT', 'text_gold')):
    one(name, id_)
info = S.find(nodes, 'grp_info')
inv = S.find(nodes, 'grp_inventory')
areas = lambda g: sorted([c for c in g.children if c.type == 'AREA'], key=lambda c: int(c.id) if c.id.isdigit() else 0)
L.append('static const SmRect SM_STALL[12] = {\n%s };\n' % ',\n'.join('    ' + R(a) for a in areas(info)))
L.append('static const SmRect SM_BAG[28] = {\n%s };\n' % ',\n'.join('    ' + R(a) for a in areas(inv)))
with open(os.path.join(HERE, 'slave_layout.h'), 'w') as f:
    f.write(''.join(L))
print('slave skin ->', OUT, len(areas(info)), len(areas(inv)))
