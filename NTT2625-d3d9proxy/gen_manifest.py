# Regenerates manifest_hashes.h from the client's Data\*.tbl and JstKO\**\*.pus files.
#
# Run this (and rebuild + redistribute d3d9.dll) every time one of those files changes on
# purpose (a tbl rename, a new .pus skin, etc.) -- otherwise every client still running the
# old DLL keeps the old hashes, which is fine (they only compare against their own build's
# baked-in list), but any client that gets the NEW DLL without the matching NEW data files
# will look tampered and get kicked by client_integrity.rs. Keep the DLL and the data files
# that go with it together when you hand them out.
#
# Usage: python gen_manifest.py [client_dir]   (default: D:\ai\JstKO Client)
import hashlib
import os
import sys

CLIENT_DIR = sys.argv[1] if len(sys.argv) > 1 else r'D:\ai\JstKO Client'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'manifest_hashes.h')


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def collect():
    entries = []
    data_dir = os.path.join(CLIENT_DIR, 'Data')
    for name in sorted(os.listdir(data_dir)):
        if name.lower().endswith('.tbl'):
            full = os.path.join(data_dir, name)
            entries.append(('Data\\' + name, full))
    jstko_dir = os.path.join(CLIENT_DIR, 'JstKO')
    for root, _dirs, files in os.walk(jstko_dir):
        for name in sorted(files):
            if name.lower().endswith('.pus'):
                full = os.path.join(root, name)
                rel = 'JstKO\\' + os.path.relpath(full, jstko_dir)
                entries.append((rel, full))
    entries.sort(key=lambda e: e[0].lower())
    return entries


def main():
    entries = collect()
    lines = [
        '// Auto-generated by gen_manifest.py -- do not edit by hand.',
        '// Regenerate (and rebuild + redistribute d3d9.dll together with these data files)',
        '// whenever a tracked Data\\*.tbl or JstKO\\**\\*.pus file changes on purpose.',
        '#pragma once',
        '',
        'struct ManifestEntry { const char* path; const char* sha256; };',
        '',
        'static const ManifestEntry MANIFEST[] = {',
    ]
    for rel, full in entries:
        digest = sha256_of(full)
        esc = rel.replace('\\', '\\\\')
        lines.append('    { "%s", "%s" },' % (esc, digest))
    lines.append('};')
    lines.append('')
    lines.append('static const int MANIFEST_COUNT = sizeof(MANIFEST) / sizeof(MANIFEST[0]);')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %d entries to %s' % (len(entries), OUT))


if __name__ == '__main__':
    main()
