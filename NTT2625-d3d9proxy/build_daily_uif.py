"""Daily Quest panel skin from the supplied re_dailyquest.uif (uif_in\\).
Output: daily_ui\\*.pus + daily_layout.h   (client folder: HopeGuard\\daily_ui)
Usage: python build_daily_uif.py
"""
import os

import uifskin as S

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'daily_ui')
OFF = (1, 0)
W, H = 888, 582

nodes = S.load_uif('re_dailyquest.uif')
for e in S.walk(nodes):
    if e.type == 'STRING' and e.text == 'Time':
        e.text = 'Kills'            # the column shows kills / needed
DYN_STR = ('txt_quest_', 'text_page', 'text_quest_name', 'text_zone', 'text_hunt_', 'str_count', 'str_name')


def dynamic(e):
    if e.type == 'STRING' and e.id.startswith(DYN_STR):
        return True
    if e.type == 'IMAGE' and e.id == 'icon':
        return True
    if e.type == 'BUTTON' and (e.id.startswith('btn_selectquest') or e.id in ('btn_close', 'btn_cancel')):
        return True
    return False


bg = S.compose(nodes, (W, H), OFF, skip=dynamic)
S.save_pus(bg, os.path.join(OUT, 'bg.pus'))
bg.save(os.path.join(HERE, '..', 'uif_out', 'daily_bg.png'))

# button / row states
row0 = S.find(nodes, 'btn_selectquest00')
for st, name in ((1, 'row_a'), (2, 'row_b')):
    img = S.state_image(row0, st)
    S.save_pus(img, os.path.join(OUT, name + '.pus'))
for bid, prefix in (('btn_close', 'close'), ('btn_cancel', 'cancel')):
    b = S.find(nodes, bid)
    for st, k in ((0, 'n'), (1, 'd'), (2, 'o')):
        S.save_pus(S.state_image(b, st), os.path.join(OUT, '%s_%s.pus' % (prefix, k)))

L = []
add = lambda n, r: L.append(S.header_line(n, r))
L.append('// Generated by build_daily_uif.py from uif_in\\re_dailyquest.uif -- do not edit by hand.\n#pragma once\n')
L.append('static const int DQ_W = %d, DQ_H = %d;\n' % (W, H))
rows = [S.find(nodes, 'btn_selectquest%02d' % i) for i in range(15)]
L.append('static const int DQ_ROWS = 15;\n')
L.append('static const int DQ_ROW_Y[15] = { %s };\n' % ', '.join(str(r.rect[1]) for r in rows))
L.append('static const int DQ_ROW_H = %d;\n' % (rows[0].rect[3] - rows[0].rect[1]))
L.append('static const int DQ_ROW_L = %d, DQ_ROW_R = %d;\n' % (41 + OFF[0], 652 + OFF[0]))
g0 = S.find(nodes, 'group_quest_00')
cols = {}
for c in g0.children:
    if c.type == 'STRING':
        cols[c.id] = c.rect
for key, name in (('txt_quest_title', 'COL_NAME'), ('txt_quest_status', 'COL_STATUS'), ('txt_quest_time', 'COL_TIME'),
                  ('txt_quest_type', 'COL_TYPE'), ('txt_quest_zone', 'COL_ZONE')):
    l, t, r, b = cols[key]
    L.append('static const int DQ_%s[2] = { %d, %d };\n' % (name, l + OFF[0], r + OFF[0]))
for nid, name in (('text_page', 'PAGE'), ('text_quest_name', 'QNAME'), ('text_zone', 'QZONE')):
    add('DQ_' + name, S.rect_of(S.find(nodes, nid), OFF))
add('DQ_BTN_PREV', S.rect_of(S.find(nodes, 'btn_previouspage'), OFF))
add('DQ_BTN_NEXT', S.rect_of(S.find(nodes, 'btn_nextpage'), OFF))
add('DQ_BTN_CLOSE', S.rect_of(S.find(nodes, 'btn_close'), OFF))
add('DQ_BTN_CANCEL', S.rect_of(S.find(nodes, 'btn_cancel'), OFF))
for kind, prefix in (('Hunt', 'HUNT'), ('Reward', 'REW')):
    for i in range(1, 5):
        base = S.find(nodes, '%s%d' % (kind, i))
        kids = list(S.walk(base.children))
        icon = next(k for k in kids if k.id == 'icon')
        nm = next(k for k in kids if k.id in ('text_hunt_name', 'str_name'))
        cn = next(k for k in kids if k.id in ('text_hunt_count', 'str_count'))
        add('DQ_%s%d_ICON' % (prefix, i), S.rect_of(icon, OFF))
        add('DQ_%s%d_NAME' % (prefix, i), S.rect_of(nm, OFF))
        add('DQ_%s%d_COUNT' % (prefix, i), S.rect_of(cn, OFF))
        add('DQ_%s%d_BOX' % (prefix, i), S.rect_of(base, OFF))
add('DQ_MSG', (88 + OFF[0], 544, 600 + OFF[0], 574))
with open(os.path.join(HERE, 'daily_layout.h'), 'w') as f:
    f.write(''.join(L))
print('daily uif skin ->', OUT)
