# Regenerates manifest_hashes.h from the client's Data\*.tbl files only (JstKO\**\*.pus was
# dropped from this check: the live game process was reading different bytes for a lot of these
# than any outside tool -- certutil included -- ever saw, cause unresolved, so they're not worth
# the false-positive risk; stat/price/drop-table tampering is the actual threat this guards
# against anyway).
#
# Run this (and rebuild + redistribute d3d9.dll) every time a tbl file changes on purpose (an
# item rename, etc.) -- otherwise every client still running the old DLL keeps the old hashes,
# which is fine (they only compare against their own build's baked-in list), but any client that
# gets the NEW DLL without the matching NEW tbl files will look tampered and get kicked by
# client_integrity.rs. Keep the DLL and the Data\*.tbl files that go with it together when you
# hand them out.
#
# It ALSO writes patch_version.h (PATCH_VERSION, baked into d3d9.dll; the DLL raises Server.ini
# [Version] Files= to it at game start so the launcher never re-downloads old patches).
# RELEASE ORDER: 1) decide new version N, 2) python gen_manifest.py --version N (or set "version"
# in patch_state.json to N first), 3) build_new.bat, 4) install the DLL, 5) python
# package_patch_zip.py --consolidate --first F --version N. The DLL must be built AFTER step 2.
#
# Usage: python gen_manifest.py [--version N] [client_dir]   (default dir: D:\ai\JstKO Client;
#        default N: "version" in patch_state.json)
import hashlib
import os
import sys

_args = sys.argv[1:]
PATCH_VERSION = None
if '--version' in _args:
    _i = _args.index('--version')
    PATCH_VERSION = int(_args[_i + 1])
    del _args[_i:_i + 2]
CLIENT_DIR = _args[0] if _args else r'D:\ai\JstKO Client'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'manifest_hashes.h')


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def collect():
    entries = []
    data_dir = os.path.join(CLIENT_DIR, 'Data')
    for name in sorted(os.listdir(data_dir)):
        if name.lower().endswith('.tbl'):
            full = os.path.join(data_dir, name)
            entries.append(('Data\\' + name, full))
    entries.sort(key=lambda e: e[0].lower())
    return entries


def main():
    entries = collect()
    lines = [
        '// Auto-generated by gen_manifest.py -- do not edit by hand.',
        '// Regenerate (and rebuild + redistribute d3d9.dll together with these data files)',
        '// whenever a tracked Data\\*.tbl file changes on purpose.',
        '#pragma once',
        '',
        'struct ManifestEntry { const char* path; const char* sha256; };',
        '',
        'static const ManifestEntry MANIFEST[] = {',
    ]
    for rel, full in entries:
        digest = sha256_of(full)
        esc = rel.replace('\\', '\\\\')
        lines.append('    { "%s", "%s" },' % (esc, digest))
    lines.append('};')
    lines.append('')
    lines.append('static const int MANIFEST_COUNT = sizeof(MANIFEST) / sizeof(MANIFEST[0]);')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %d entries to %s' % (len(entries), OUT))
    ver = PATCH_VERSION
    if ver is None:
        import json
        with open(os.path.join(HERE, 'patch_state.json'), encoding='utf-8') as f:
            ver = int(json.load(f)['version'])
    with open(os.path.join(HERE, 'patch_version.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Auto-generated by gen_manifest.py -- do not edit by hand.\n#pragma once\n#define PATCH_VERSION %d\n' % ver)
    print('wrote patch_version.h: PATCH_VERSION %d' % ver)


if __name__ == '__main__':
    main()
