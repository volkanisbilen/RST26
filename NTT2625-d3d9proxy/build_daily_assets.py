"""Daily Quest panel skin (daily_panel.cpp). Procedural dark/bronze boxes only, so it needs no game atlas files.
Output: daily_ui\\*.pus + daily_layout.h   (client folder: HopeGuard\\daily_ui)
Usage: python build_daily_assets.py
"""
import os
from PIL import Image, ImageDraw
import kopanel as K

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'daily_ui')

W, H = 320, 400
L = {}
def r(name, x0, y0, x1, y1): L[name] = (x0, y0, x1, y1); return (x0, y0, x1, y1)

def box(w, h, fill=(22, 20, 18, 250), edge=(120, 96, 52, 255), inner=(52, 44, 30, 255)):
    im = Image.new('RGBA', (w, h), fill); d = ImageDraw.Draw(im)
    d.rectangle((0, 0, w - 1, h - 1), outline=edge); d.rectangle((2, 2, w - 3, h - 3), outline=inner)
    return im

def button(w, h, top, bot, edge):
    im = Image.new('RGBA', (w, h)); d = ImageDraw.Draw(im)
    for y in range(h):
        t = y / max(1, h - 1)
        d.line((0, y, w, y), fill=tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3)) + (255,))
    d.rectangle((0, 0, w - 1, h - 1), outline=edge)
    return im

bg = box(W, H)
def put(img, rect): bg.alpha_composite(img, (rect[0], rect[1]))

put(button(220, 26, (60, 90, 150), (30, 52, 100), (140, 150, 190)), r('title', 40, 8, 260, 34))
r('close', 288, 9, 312, 33)
put(box(W - 20, 144, (14, 13, 12, 255)), r('list', 10, 42, W - 10, 186))
r('scroll_up', 294, 44, 308, 58)
r('scroll_dn', 294, 170, 308, 184)
put(box(W - 20, 146, (14, 13, 12, 255)), r('detail', 10, 192, W - 10, 338))
r('bar', 16, 316, W - 16, 332)
r('msg', 10, 342, W - 10, 358)
BW, BH = 72, 26
r('btn_accept', 10, 364, 10 + BW, 364 + BH)
r('btn_abandon', 86, 364, 86 + BW, 364 + BH)
r('btn_claim', 162, 364, 162 + BW, 364 + BH)
r('btn_close', 238, 364, 238 + BW, 364 + BH)

os.makedirs(OUT, exist_ok=True)
K.save_pus(bg, os.path.join(OUT, 'bg.pus'))
styles = {'n': ((120, 70, 40), (70, 38, 22), (200, 150, 80)), 'o': ((160, 100, 56), (96, 56, 30), (255, 210, 120)),
          'd': ((60, 34, 20), (96, 56, 30), (200, 150, 80)), 'x': ((52, 50, 48), (36, 35, 34), (80, 78, 74))}
for k, (a, b, e) in styles.items():
    K.save_pus(button(BW, BH, a, b, e), os.path.join(OUT, 'btn_%s.pus' % k))
for k, (a, b, e) in {'n': ((120, 40, 40), (70, 20, 20), (200, 120, 100)), 'o': ((170, 60, 56), (100, 30, 30), (255, 180, 140)),
                     'd': ((70, 20, 20), (100, 30, 30), (200, 120, 100))}.items():
    K.save_pus(button(24, 24, a, b, e), os.path.join(OUT, 'close_%s.pus' % k))

with open(os.path.join(HERE, 'daily_layout.h'), 'w') as f:
    f.write('// Generated by build_daily_assets.py -- do not edit by hand.\n#pragma once\n')
    f.write('static const int DQ_W = %d, DQ_H = %d;\n' % (W, H))
    for k, v in L.items():
        f.write('static const int DQ_%s[4] = { %d, %d, %d, %d };\n' % ((k.upper(),) + v))
print('daily skin ->', OUT)
